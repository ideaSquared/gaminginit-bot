import { createLogger, type Sink } from '@ideasquared/log';

// Every field the bot may log. None identifies a player: no names, Steam IDs, Discord user IDs, chat text, IPs or
// tokens. Counts, map and faction names, outcomes and rule ids are what is left to describe an event.
export const createBotLog = (sink?: Sink) =>
  createLogger({
    service: 'wardogs-discord-bot',
    fields: [
      'action',
      'added',
      'ballots',
      'banned',
      'bans',
      'challengeId',
      'cheats',
      'choice',
      'command',
      'count',
      'day',
      'days',
      'enabled',
      'facts',
      'from',
      'hadWinner',
      'headshots',
      'infantryMaps',
      'item',
      'join',
      'kills',
      'kind',
      'lines',
      'list',
      'map',
      'maps',
      'maxPlayers',
      'member',
      'messageId',
      'minLength',
      'minutes',
      'missing',
      'nextMap',
      'noRain',
      'offMaps',
      'outcome',
      'period',
      'phase',
      'playedLately',
      'players',
      'playersBefore',
      'quiet',
      'recent',
      'records',
      'removed',
      'replaced',
      'risk',
      'roleId',
      'rotation',
      'route',
      'rule',
      'score',
      'season',
      'setup',
      'since',
      'slot',
      'staffSpotsAdded',
      'staffSpotsEnded',
      'staged',
      'status',
      'steam',
      'target',
      'teamKills',
      'tier',
      'unread',
      'vehicleSuicides',
      'via',
      'voteId',
      'what',
      'why',
      'withInfantry',
      'withModes',
    ],
    ...(sink === undefined ? {} : { sink }),
  });

export const log = createBotLog();

export type Log = ReturnType<typeof createBotLog>;
